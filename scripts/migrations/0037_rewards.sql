-- 0037_rewards.sql — Feb 2026
--
-- LinkedIn-share reward engine. When a learner completes a specific module
-- project (module 1, 10, final, etc.) or a specific capstone (e.g. CAP-01),
-- a `master_rewards` row is presented on the completion page. If the user
-- clicks "I've shared on LinkedIn", we record a `user_reward_claims` row
-- and let them download the resource file from Supabase Storage.
--
-- The admin panel (new "Rewards" tab) is the sole UI for CRUD; there is no
-- learner-side edit path.

BEGIN;

-- 1. master_rewards ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.master_rewards (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title               text NOT NULL,
  description         text,
  linkedin_message    text,                       -- pre-composed post text
  trigger_type        text NOT NULL,              -- 'module_complete' | 'capstone_complete'
  trigger_ref_id      uuid NOT NULL,              -- master_modules.id OR master_capstone_projects.id
  resource_file_path  text,                       -- storage key inside the `rewards` bucket
  resource_file_name  text,                       -- original filename (for display + download)
  resource_mime       text,
  resource_size_bytes bigint,
  order_index         int NOT NULL DEFAULT 100,
  is_active           boolean NOT NULL DEFAULT true,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT master_rewards_trigger_type_ck
    CHECK (trigger_type IN ('module_complete', 'capstone_complete'))
);

CREATE INDEX IF NOT EXISTS master_rewards_trigger_idx
  ON public.master_rewards(trigger_type, trigger_ref_id) WHERE is_active;

-- 2. user_reward_claims ------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.user_reward_claims (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     uuid NOT NULL,
  reward_id   uuid NOT NULL REFERENCES public.master_rewards(id) ON DELETE CASCADE,
  shared_at   timestamptz NOT NULL DEFAULT now(),
  claimed_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_reward_claims_uq UNIQUE (user_id, reward_id)
);

CREATE INDEX IF NOT EXISTS user_reward_claims_user_idx
  ON public.user_reward_claims(user_id);

-- 3. RLS ---------------------------------------------------------------------
ALTER TABLE public.master_rewards      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_reward_claims  ENABLE ROW LEVEL SECURITY;

-- Learners can read active rewards (needed to render the CTA card).
DROP POLICY IF EXISTS "rewards_public_read_active" ON public.master_rewards;
CREATE POLICY "rewards_public_read_active"
  ON public.master_rewards
  FOR SELECT
  USING (is_active = true);

-- Only backend (service_role) writes. No FE INSERT/UPDATE/DELETE.
-- (Service role bypasses RLS, so no explicit write policy is needed.)

-- Learners can read + insert their own claims.
DROP POLICY IF EXISTS "user_reward_claims_self_read" ON public.user_reward_claims;
CREATE POLICY "user_reward_claims_self_read"
  ON public.user_reward_claims
  FOR SELECT
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "user_reward_claims_self_insert" ON public.user_reward_claims;
CREATE POLICY "user_reward_claims_self_insert"
  ON public.user_reward_claims
  FOR INSERT
  WITH CHECK (auth.uid() = user_id);

-- 4. Storage bucket ----------------------------------------------------------
-- Private bucket. Reads happen through signed URLs generated by the backend
-- so a claim record is required before the file leaks.
INSERT INTO storage.buckets (id, name, public)
VALUES ('rewards', 'rewards', false)
ON CONFLICT (id) DO NOTHING;

-- Nobody reads the bucket directly from the FE; the backend generates signed
-- URLs. No SELECT policy needed. Uploads happen via service_role.

-- 5. Seed defaults -----------------------------------------------------------
-- Skip auto-seeding because there are multiple learning paths and each has
-- its own Module 1 / 10 / 23 / CAP-01. Admins should create rewards from
-- the new "Rewards" tab (fast — 4 clicks per reward).

COMMIT;
